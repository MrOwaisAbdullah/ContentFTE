"""Render docs/improvement-status.md - the single status board for docs/improvement-plan-2026-11.md.

Where progress is marked:  docs/improvement-status.json   (the ONLY file to edit by hand)
Where it is read:          docs/improvement-status.md      (generated - do not edit)
The finding list itself:   docs/improvement-plan-2026-11.md (its ID tables)

    python scripts/improvement_status.py          # regenerate the markdown
    python scripts/improvement_status.py --check  # exit 1 if a finding has no status, a status has no
                                                  # finding, or the markdown is stale (CI / pytest)

Statuses
    done        fixed in code and covered by a test (or verified live)
    partial     part of it is fixed; `note` says what is left
    open        not started
    decision    needs the owner's choice before code (see the plan's "decisions" table)
    owner       an action only the owner can take (rotate a key, change a GitHub setting)
    other-repo  lives in a different repository (the live website's frontend)
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter, OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLAN = ROOT / "docs" / "improvement-plan-2026-11.md"
DATA = ROOT / "docs" / "improvement-status.json"
OUT = ROOT / "docs" / "improvement-status.md"

STATUSES = ("done", "partial", "open", "decision", "owner", "other-repo")
ICON = {"done": "✅", "partial": "🟡", "open": "⬜", "decision": "🧭", "owner": "👤", "other-repo": "↗️"}
AREAS = OrderedDict([
    ("SEC", "Security"), ("ENG", "Engine core"), ("PIPE", "Agent pipeline"), ("ADP", "Adapters & SDK"),
    ("SEO", "SEO & content quality"), ("FE", "Live website frontend"), ("CON", "Operator console"),
    ("TEN", "Multi-tenancy"), ("OPS", "Operations"),
])
ROW = re.compile(r"^\| ((?:SEC|ENG|PIPE|ADP|SEO|FE|CON|TEN|OPS)-\d+) \|(.*)$")
SEVERITY = re.compile(r"\b(Critical|High|Medium|Low)\b")


def plan_findings() -> "OrderedDict[str, dict]":
    """{ID: {severity, title}} from the plan's finding tables (first row per ID wins)."""
    found: "OrderedDict[str, dict]" = OrderedDict()
    for line in PLAN.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if not m or m.group(1) in found:
            continue
        cells = [c.strip() for c in m.group(2).split(" | ")]
        sev = SEVERITY.search(cells[0]) if cells else None
        # every finding table is: ID | Severity | Status | Finding | ...  -> the finding is the 3rd cell
        prose = cells[2] if len(cells) > 2 else ""
        title = re.sub(r"[*`]", "", prose).split(". ")[0].strip()
        found[m.group(1)] = {"severity": sev.group(1) if sev else "", "title": (title[:110] + "…") if len(title) > 110 else title}
    return found


def load_status() -> dict:
    return json.loads(DATA.read_text(encoding="utf-8"))


def problems(findings: dict, status: dict) -> list[str]:
    out = []
    entries = status.get("items", {})
    for fid in findings:
        if fid not in entries:
            out.append(f"{fid}: in the plan but missing from improvement-status.json")
    for fid, e in entries.items():
        if fid not in findings:
            out.append(f"{fid}: in improvement-status.json but not in the plan")
        if e.get("status") not in STATUSES:
            out.append(f"{fid}: invalid status {e.get('status')!r} (use one of {', '.join(STATUSES)})")
        if e.get("status") in ("partial", "decision", "owner") and not e.get("note"):
            out.append(f"{fid}: status '{e['status']}' needs a note saying what is left / what is needed")
    return out


def render(findings: dict, status: dict) -> str:
    items = status["items"]
    branches = status.get("branches", {})
    total = Counter(items[f]["status"] for f in findings if f in items)
    lines = [
        "# Improvement status board",
        "",
        "> **Generated** by `scripts/improvement_status.py` from `docs/improvement-status.json` and the finding "
        "tables in [`improvement-plan-2026-11.md`](improvement-plan-2026-11.md). **Do not edit this file.** "
        "To mark progress, change a `status` in `docs/improvement-status.json`, then run "
        "`python scripts/improvement_status.py`. `tests/test_improvement_status.py` fails if a finding has no "
        "status or this page is stale.",
        "",
        f"**{len(findings)} findings** · " + " · ".join(
            f"{ICON[s]} {s} {total.get(s, 0)}" for s in STATUSES),
        "",
        "Legend: ✅ done · 🟡 partial · ⬜ open · 🧭 needs your decision · 👤 needs an owner action · ↗️ other repo",
        "",
        "## Where the work lives",
        "",
        "| Branch | What it contains |",
        "|---|---|",
    ]
    for key, b in branches.items():
        lines.append(f"| `{b['name']}` | {b['summary']} |")
    lines += ["", "## By area", "", "| Area | " + " | ".join(ICON[s] for s in STATUSES) + " | Total |",
              "|---|" + "---|" * (len(STATUSES) + 1)]
    for code, label in AREAS.items():
        ids = [f for f in findings if f.startswith(code + "-")]
        c = Counter(items[f]["status"] for f in ids if f in items)
        lines.append(f"| {label} | " + " | ".join(str(c.get(s, 0)) for s in STATUSES) + f" | {len(ids)} |")

    sev_rank = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3, "": 4}
    todo = [f for f in findings if items.get(f, {}).get("status") in ("open", "partial", "decision", "owner")]
    todo.sort(key=lambda f: (sev_rank.get(findings[f]["severity"], 4), f))
    lines += ["", "## What is still to do (most severe first)", ""]
    if todo:
        lines += ["| ID | Sev | Status | What is left | Finding |", "|---|---|---|---|---|"]
        for f in todo:
            e = items[f]
            lines.append(f"| {f} | {findings[f]['severity'] or '-'} | {ICON[e['status']]} {e['status']} | "
                         f"{e.get('note') or '-'} | {findings[f]['title']} |")
    else:
        lines.append("Nothing outstanding.")

    for code, label in AREAS.items():
        ids = [f for f in findings if f.startswith(code + "-")]
        lines += ["", f"## {label}", "", "| ID | Sev | Status | Branch | Note | Finding |", "|---|---|---|---|---|---|"]
        for f in ids:
            e = items.get(f, {"status": "open"})
            br = branches.get(e.get("branch", ""), {}).get("name", "")
            lines.append(f"| {f} | {findings[f]['severity'] or '-'} | {ICON.get(e['status'], '?')} {e['status']} | "
                         f"{('`' + br + '`') if br else '-'} | {e.get('note') or '-'} | {findings[f]['title']} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    findings, status = plan_findings(), load_status()
    errs = problems(findings, status)
    text = render(findings, status)
    if "--check" in argv:
        if OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            errs.append("docs/improvement-status.md is stale - run: python scripts/improvement_status.py")
        for e in errs:
            print("ERROR:", e)
        return 1 if errs else 0
    if errs:
        for e in errs:
            print("ERROR:", e)
        return 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(findings)} findings)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
