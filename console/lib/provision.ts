import "server-only";
import { randomBytes } from "node:crypto";

export interface ProvisionInput {
  slug: string;
  name: string;
  siteType: string; // wordpress | custom
  baseUrl: string;
  wpUser: string;
  wpPassword: string;
  sdkKey: string; // empty -> wizard generates
}

export interface ProvisionResult {
  slug: string;
  env: string;
  sdkKey: string;
}

/** Build the full instance-2 env (spec §4 key inventory) for download. */
export function generateInstanceEnv(input: ProvisionInput): ProvisionResult {
  const slug = input.slug.trim();
  const baseUrl = input.baseUrl.trim().replace(/\/+$/, "");
  const sdkKey = (input.sdkKey || "").trim() || randomBytes(16).toString("hex");
  const stamp = new Date().toISOString().slice(0, 10);

  const env = [
    `# ContentFTE instance env — generated by the console /provision wizard (${stamp})`,
    `# Site: ${slug} (${input.name.trim() || slug}) — ${baseUrl || "no URL yet"}`,
    `# Paste every <…> placeholder before starting the process:`,
    `#   uvicorn main:app --port <port>`,
    ``,
    `# --- Tenancy / identity ---`,
    `TENANCY_MODE=isolated`,
    `DEFAULT_SITE_SLUG=${slug}`,
    baseUrl ? `SITE_BASE_URL=${baseUrl}` : `SITE_BASE_URL=<https://yourdomain.com>`,
    ``,
    `# --- Database (paste your Neon URL; sqlite fallback for local dev) ---`,
    `DATABASE_URL=<paste-neon-database-url>`,
    ``,
    `# --- Postgres-only instance: no Google Sheets at all ---`,
    `SHEETS_ENABLED=0`,
    `STORE_READ_SOURCE=postgres`,
    ``,
    `# --- Engine auth ---`,
    `API_KEY=<paste-long-random-string>`,
    `SDK_MASTER_KEY=${sdkKey}`,
    ``,
    `# --- WordPress (${input.siteType}) ---`,
    `WP_BASE_URL=${baseUrl || "<https://yourdomain.com>"}`,
    `WP_USERNAME=${input.wpUser.trim() || "<wp-admin-username>"}`,
    `WP_APP_PASSWORD=${(input.wpPassword || "").trim() || "<paste-wp-application-password>"}`,
    ``,
    `# --- Models (new free-tier accounts; exact names, no -latest aliases) ---`,
    `GEMINI_API_KEY=<paste-gemini-key>`,
    `OPENROUTER_API_KEY=<paste-openrouter-key>`,
    ``,
    `# --- Images (new Cloudflare Workers account) ---`,
    `CLOUDFLARE_ACCOUNT_ID=<paste-cloudflare-account-id>`,
    `CLOUDFLARE_API_TOKEN=<paste-cloudflare-api-token>`,
    ``,
    `# --- Research ---`,
    `TAVILY_API_KEY=<paste-tavily-key>`,
    ``,
    `# --- Optional ---`,
    `# INDEXNOW_KEY=`,
    `# SEARCH_CONSOLE_SITE_URL=${baseUrl ? `${baseUrl}/` : "https://yourdomain.com/"}`,
    `# AUTHOR_PROFILE_API_URL=${baseUrl ? `${baseUrl}/api/profile` : "https://yourdomain.com/api/profile"}`,
    `# DISCORD_WEBHOOK_URL=`,
    `# SDK_CORS_ORIGINS=http://localhost:3000`,
    ``,
  ].join("\n");

  return { slug, env, sdkKey };
}
